//! The Discord SKU resource.
//!
//! SKUs represent premium offerings that users or guilds can purchase. See
//! [Discord's SKU resource][resource] for details.
//!
//! [resource]: https://docs.discord.com/developers/resources/sku

mod flags;
mod kind;

use cordion_macro::IdTarget;
pub use flags::SkuFlags;
pub use kind::SkuKind;
use serde::{Deserialize, Serialize};

use crate::application::ApplicationId;
use crate::id::{Id, Identifiable};

/// The ID of a [`Sku`].
pub type SkuId = Id<Sku>;

/// A stock-keeping unit representing a premium offering.
///
/// See [Discord's SKU object][object] for details.
///
/// [object]: https://docs.discord.com/developers/resources/sku#sku-object
#[derive(Clone, PartialEq, Eq, IdTarget, Serialize, Deserialize, Debug)]
pub struct Sku {
    /// The SKU's ID.
    pub id: Id<Sku>,

    /// The purchase type, serialized as `type`.
    #[serde(rename = "type")]
    pub kind: SkuKind,

    /// The ID of the parent application.
    pub application_id: ApplicationId,

    /// The customer-facing product name.
    pub name: String,

    /// The URL slug generated by Discord from the product name.
    pub slug: String,

    /// Purchase availability and subscription access flags.
    pub flags: SkuFlags,
}

impl Identifiable for Sku {
    #[inline]
    fn id(&self) -> Id<Self> {
        self.id
    }
}
