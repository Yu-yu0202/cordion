use serde::{Deserialize, Serialize};

use crate::application::ApplicationId;
use crate::monetization::sku::SkuId;

/// A partial application embedded in an invite's `target_application` field.
///
/// Discord describes this value only as a partial application object and does
/// not publish a dedicated schema for it. Consequently, this type models a
/// conservative subset of the full application object: only
/// [`id`](Self::id) and [`name`](Self::name) are required, and the remaining
/// fields are omitted during serialization when absent. Fields that are not
/// modeled here are ignored during deserialization.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize, Debug)]
pub struct PartialApplication {
    /// The application's ID.
    pub id: ApplicationId,

    /// The application's name.
    pub name: String,

    /// The application's icon hash.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub icon: Option<String>,

    /// The application's description.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,

    /// The application's cover image hash.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub cover_image: Option<String>,

    /// The ID of the application's primary SKU.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub primary_sku_id: Option<SkuId>,

    /// The URL slug generated by Discord from the application name.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub slug: Option<String>,
}
